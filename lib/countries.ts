const byCode = new Map(COUNTRIES.map((country) => [country.code, country]));
const bySlug = new Map(COUNTRIES.map((country) => [country.slug, country]));

export function getCountry(code: string | undefined | null): CountryInfo | undefined {
  if (!code) return undefined;
  return byCode.get(code.toUpperCase());
}

export function getCountryBySlug(slug: string | undefined | null): CountryInfo | undefined {
  if (!slug) return undefined;
  return bySlug.get(slug.toLowerCase());
}

export function countryName(code: string | undefined | null): string {
  return getCountry(code)?.name ?? code ?? "";
}

export function countriesInRegion(region: RegionId): CountryInfo[] {
  return COUNTRIES.filter((country) => country.region === region).sort((a, b) => a.name.localeCompare(b.name));
}

